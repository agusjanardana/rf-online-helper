export type EnhancementGroup = "1-5" | "6-7" | "8-10" | "11-14" | "15";

export function getEnhancementGroup(enhancement: number): EnhancementGroup {
  if (enhancement <= 5) return "1-5";
  if (enhancement <= 7) return "6-7";
  if (enhancement <= 10) return "8-10";
  if (enhancement <= 14) return "11-14";
  return "15";
}

